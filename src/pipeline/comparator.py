"""A/B comparison between two models/systems over the same dataset."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from src.datasets.builder import EvalDataset
from src.models import EvaluationReport
from src.pipeline.runner import EvaluationRunner


@dataclass
class MetricComparison:
    metric: str
    mean_a: float
    mean_b: float
    delta: float  # mean_b - mean_a
    winner: str  # label_a | label_b | "tie"


@dataclass
class ComparisonReport:
    label_a: str
    label_b: str
    report_a: EvaluationReport
    report_b: EvaluationReport
    comparisons: list[MetricComparison] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "label_a": self.label_a,
            "label_b": self.label_b,
            "pass_rate_a": round(self.report_a.pass_rate, 4),
            "pass_rate_b": round(self.report_b.pass_rate, 4),
            "comparisons": [
                {
                    "metric": c.metric,
                    "mean_a": round(c.mean_a, 4),
                    "mean_b": round(c.mean_b, 4),
                    "delta": round(c.delta, 4),
                    "winner": c.winner,
                }
                for c in self.comparisons
            ],
        }


class ModelComparator:
    """Runs the same evaluator suite over two datasets and diffs the results.

    `dataset_a`/`dataset_b` should contain answers to the *same*
    questions generated by the two systems under comparison.
    """

    def __init__(self, runner: EvaluationRunner) -> None:
        self.runner = runner
        self._higher_is_better = {e.name: e.higher_is_better for e in runner.evaluators}

    def compare(
        self,
        dataset_a: EvalDataset | list,
        dataset_b: EvalDataset | list,
        label_a: str = "model_a",
        label_b: str = "model_b",
    ) -> ComparisonReport:
        report_a = self.runner.run(dataset_a)
        report_b = self.runner.run(dataset_b)

        metric_names = sorted(set(report_a.metric_names()) | set(report_b.metric_names()))
        comparisons = []
        for name in metric_names:
            summary_a = report_a.metric_summary(name)
            summary_b = report_b.metric_summary(name)
            mean_a = summary_a.get("mean", 0.0)
            mean_b = summary_b.get("mean", 0.0)
            delta = mean_b - mean_a
            higher_is_better = self._higher_is_better.get(name, True)

            if abs(delta) < 1e-9:
                winner = "tie"
            elif (delta > 0) == higher_is_better:
                winner = label_b
            else:
                winner = label_a

            comparisons.append(
                MetricComparison(metric=name, mean_a=mean_a, mean_b=mean_b, delta=delta, winner=winner)
            )

        return ComparisonReport(
            label_a=label_a,
            label_b=label_b,
            report_a=report_a,
            report_b=report_b,
            comparisons=comparisons,
        )
